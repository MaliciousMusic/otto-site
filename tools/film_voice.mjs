// node tools/film_voice.mjs [lang]   records the film's narration with Piper, one MP3 per line.
// Needs Piper and a voice model: PIPER (default ~/.local/share/piper/piper/piper) and
// VOICE_fr / VOICE_en (default ~/.local/share/piper/<voice>.onnx). Writes src/assets/film/<lang>/
// and src/data/film-audio.js. A line whose text changed gets a new file; the player only plays
// audio whose hash matches the current text, so stale audio is never heard.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, existsSync, readdirSync, rmSync, writeFileSync, readFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { join } from 'node:path';
import { scenes } from '../src/data/film.js';

const HOME = join(homedir(), '.local/share/piper');
const PIPER = process.env.PIPER || join(HOME, 'piper/piper');
const VOICES = { fr: process.env.VOICE_fr || join(HOME, 'fr_FR-siwis-medium.onnx'), en: process.env.VOICE_en || join(HOME, 'en_US-lessac-medium.onnx') };
const OUT = 'src/assets/film', MAP = 'src/data/film-audio.js';
export const hash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 10);

const old = existsSync(MAP) ? JSON.parse(readFileSync(MAP, 'utf8').replace(/^[^{]*/, '').replace(/;\s*$/, '')) : {};
const langs = process.argv[2] ? [process.argv[2]] : Object.keys(VOICES).filter((l) => existsSync(VOICES[l]));
const map = { ...old };
for (const lang of langs) {
  const dir = join(OUT, lang), wav = join(tmpdir(), `otto-film-${process.pid}.wav`), keep = new Set();
  mkdirSync(dir, { recursive: true });
  map[lang] = {};
  let made = 0;
  scenes.forEach((sc, si) => sc.lines.forEach((l, k) => {
    const text = l[lang === 'fr' ? 0 : 1], h = hash(text), file = `${sc.id}-${k}-${h}.mp3`;
    keep.add(file); map[lang][`${si}.${k}`] = [file, h];
    if (existsSync(join(dir, file))) return;
    const p = spawnSync(PIPER, ['--model', VOICES[lang], '--output_file', wav, '--sentence_silence', '0.3', '--length_scale', '0.97'], { input: text, encoding: 'utf8' });
    if (p.status !== 0) throw new Error(`piper failed on ${sc.id}-${k}: ${p.stderr}`);
    const f = spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', wav, '-ac', '1', '-ar', '22050', '-b:a', '40k', '-map_metadata', '-1', join(dir, file)]);
    if (f.status !== 0) throw new Error(`ffmpeg failed on ${sc.id}-${k}`);
    made++;
  }));
  for (const f of readdirSync(dir)) if (!keep.has(f)) rmSync(join(dir, f));
  rmSync(wav, { force: true });
  console.log(`${lang}: ${keep.size} lines, ${made} recorded`);
}
writeFileSync(MAP, `// Generated by tools/film_voice.mjs. Do not edit. Line "scene.line" -> [file, hash of its text].\nexport default ${JSON.stringify(map)};\n`);
