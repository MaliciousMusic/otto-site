"""Extract the recorded results shown on the site from a checkout of the research repo.

    python3 tools/build_data.py /path/to/Powii [git-ref]

Nothing is computed here beyond reshaping: every number comes from a recorded artefact.
The default ref is the research branch that carries G02-MEASUREMENT-V1.
"""
import csv, io, json, subprocess, sys

repo = sys.argv[1]
ref = sys.argv[2] if len(sys.argv) > 2 else "origin/research/g02-semantic-identifiability-v1"


def show(path):
    return subprocess.run(["git", "-C", repo, "show", f"{ref}:{path}"],
                          check=True, capture_output=True, text=True).stdout


def rows(path):
    return list(csv.DictReader(io.StringIO(show(path))))


out = {"source": {"commit": subprocess.run(["git", "-C", repo, "rev-parse", ref], check=True,
                                           capture_output=True, text=True).stdout.strip(),
                  "record_date": "2026-10-02"}}

out["law"] = {}
for key, path in (("0.25", "E0-law-ablation-v1"), ("0.5", "E0-p50-law-ablation-v1")):
    out["law"][key] = [[int(r["seed"]), int(r["initial_clusters"]), int(r["majority_final_clusters"])]
                       for r in rows(f"results/{path}/paired_comparison.csv")]

out["orders"] = [[int(r["initial_seed"]), int(r["distinct_endpoint_count"])]
                 for r in rows("results/E0-sequential-order-replicates-v1/per_initial_condition.csv")]

out["distance"] = {}
for key, path in (("32", "E0-interface-distance-response-v1"), ("64", "E0-interface-distance-size-v1")):
    by = {}
    for r in rows(f"results/{path}/per_seed_distance_response.csv"):
        by.setdefault(r["distance_class"], []).append([int(r["seed"]), int(r["endpoint_changed"] == "True")])
    out["distance"][key] = by

org = {}
for line in show("results/ORG-01-counterfactual-closure-v2/events.jsonl").splitlines():
    e = json.loads(line)
    if e.get("record_type") != "transition" or e["replay_index"] != 1 or e["orientation"] != "p_b_to_c_a":
        continue
    trace = org.setdefault(e["condition"], [])
    if not trace:
        trace.append(e["output_before"])
    trace.append(e["output_after"])
out["org01"] = {k: "".join(map(str, v)) for k, v in org.items()}

s = json.loads(show("results/G02-MEASUREMENT-V1/summary.json"))
OBS = ["PRIMARY", "window_[8, 18]", "window_[12, 22]", "bin_width_2"]


def verdict(m, name):
    # per-path records differ in nesting between fields; find the classification for one observer
    def find(o):
        if isinstance(o, dict):
            if name in o:
                v = o[name]
                return v if isinstance(v, str) else v.get("classification")
            for v in o.values():
                r = find(v)
                if r:
                    return r
        return None
    return find(m)


out["observer"] = {str(n): [[int(verdict(s["measurements"][f"candidate_n{n}_s{i}"], o) == "PASS") for o in OBS]
                            for i in range(64)] for n in (4, 92)}
out["reversals"] = s["observer_reversals"]

with open("data/results.js", "w") as f:
    f.write("// Generated by tools/build_data.py. Do not edit.\nexport default ")
    json.dump(out, f, separators=(",", ":"))
    f.write(";\n")
print({k: (len(v) if hasattr(v, "__len__") else v) for k, v in out.items()})
for n in out["observer"]:
    v = out["observer"][n]
    print(n, [sum(p[i] for p in v) for i in range(4)])
print("changed", [sum(p[0] != p[i] for n in out["observer"] for p in out["observer"][n]) for i in range(4)],
      "distinct", sum(len(set(p)) > 1 for n in out["observer"] for p in out["observer"][n]))
print({k: (v.find("0"), v[-1]) for k, v in out["org01"].items()})
